"""Phase-4 Academy expansion: senior tracks and six forensic masterclasses.

Kept in a separate module so the original beginner curriculum in
``academy.py`` stays readable. Every card follows the same five-part shape:
plain meaning (English + Hinglish), everyday analogy, plain-words formula,
a three-line worked example and a thumb rule.
"""
from __future__ import annotations

ASOF = "3 Nov 2026"


def _card(id, title, en, hi, analogy, formula, plain, example_title, lines,
          good, careful, link, level="Advanced"):
    lines = [str(x) for x in lines][:3]
    return {
        "id": id,
        "title": title,
        "one_liner": en,
        "hinglish": hi,
        "simple": {"en": en, "hi": hi},
        "analogy": analogy,
        "formula": {
            "expression": formula,
            "plain": plain,
            "variables": [],
            "note": "Use reported numbers and disclosed prices; never guess a missing input.",
        },
        "example": {
            "title": example_title,
            "lines": lines,
            "calculation": lines[1] if len(lines) > 1 else "",
            "result": lines[-1],
            "asof": ASOF,
        },
        "thumb_rule": {"good": list(good), "careful": list(careful)},
        "body": f"{en} {analogy}",
        "pitfall": (list(careful) or ["Numbers change; always check the date."])[0],
        "link": link,
        "level": level,
    }


