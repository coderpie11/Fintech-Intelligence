def validate_sql(sql: str) -> tuple[str | None, str | None]:
    """Return (clean_sql, error). Only single SELECTs over allow-listed views."""
    s = (sql or "").strip()
    if not s:
        return None, "empty statement"
    if s.endswith(";"):
        s = s[:-1].rstrip()
    if ";" in s:
        return None, "multiple statements are not allowed"
    if not re.match(r"^(select|with)\b", s, re.I):
        return None, "only SELECT queries are allowed"
    if _FORBIDDEN.search(s):
        return None, "statement contains a forbidden keyword"
    if "--" in s or "/*" in s:
        return None, "comments are not allowed"
    tables = set(re.findall(r"\b(?:from|join)\s+([a-zA-Z_][\w]*)", s, re.I))
    unknown = {t for t in tables if t.lower() not in _ALLOWED}
    if unknown:
        return None, f"table not allowed: {', '.join(sorted(unknown))}"
    if not re.search(r"\blimit\b", s, re.I):
        s = s + " LIMIT 100"
    m = re.search(r"\blimit\s+(\d+)", s, re.I)
    if m and int(m.group(1)) > 200:
        s = re.sub(r"\blimit\s+\d+", "LIMIT 200", s, flags=re.I)
    return s, None


def run_sql(sql: str) -> dict:
    clean, err = validate_sql(sql)
    if err:
        return {"ok": False, "error": err, "sql": sql, "columns": [], "rows": []}
    try:
        with engine.connect() as conn:
            conn.exec_driver_sql("PRAGMA query_only=ON")
            res = conn.execute(text(clean))
            cols = list(res.keys())
            rows = [list(r) for r in res.fetchmany(200)]
        return {"ok": True, "sql": clean, "columns": cols, "rows": rows,
                "row_count": len(rows)}
    except Exception as e:  # noqa: BLE001
        return {"ok": False, "error": f"{type(e).__name__}: {e}"[:240],
                "sql": clean, "columns": [], "rows": []}


