def sections_of(annual: dict) -> dict:
    """Normalise the two stored shapes: {sections:{...}} or flat sections."""
    if not annual:
        return {}
    sec = annual.get("sections")
    if isinstance(sec, dict) and sec:
        return sec
    return {k: (annual.get(k) or {}) for k in ("income", "balance", "cashflow")}


def ensure_views() -> dict:
    """Recreate the read-only views once; safe to call on every boot.

    The views are dropped and recreated rather than `IF NOT EXISTS` so a schema
    change in this module is picked up without a manual database migration.
    They hold no data of their own.
    """
    made, errors = [], []
    with engine.begin() as conn:
        for name, sql in _VIEW_SQL.items():
            try:
                conn.exec_driver_sql(f"DROP VIEW IF EXISTS {name}")
                conn.exec_driver_sql(sql)
                made.append(name)
            except Exception as e:  # noqa: BLE001
                errors.append(f"{name}: {type(e).__name__}: {e}"[:180])
    return {"views": made, "errors": errors}


