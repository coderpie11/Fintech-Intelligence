_SQL_SYSTEM = (
    "You are a cautious data analyst. Convert the user's question into ONE "
    "SQLite SELECT statement over the provided views. Rules: only SELECT; only "
    "these views; never invent columns; use json-free plain columns as listed; "
    "add LIMIT 100 unless the user asks for fewer; no comments; no multiple "
    "statements. Return strict JSON: {\"sql\": \"...\", \"explanation\": \"...\"}."
)


def _schema_hint(db: Session) -> str:
    return "\n".join(f"{v}({', '.join(cols)})"
                     for v, cols in VIEW_COLUMNS.items())


def _llm_sql(question: str, db: Session) -> dict:
    prompt = (f"Available views and columns:\n{_schema_hint(db)}\n\n"
              f"Question: {question}\n\nReturn the JSON object.")
    try:
        out = LLM.complete(prompt, system=_SQL_SYSTEM, max_tokens=900,
                           json_mode=True, route="ask-dalal-sql")
    except LLM.LlmUnavailable as e:
        return {"used": False, "error": str(e)[:300], "attempts": e.attempts}
    parsed = LLM.extract_json(out.text) or {}
    sql = parsed.get("sql") or ""
    clean, err = validate_sql(sql)
    return {"used": True, "provider": out.provider, "model": out.model,
            "tier": out.tier, "sql": clean, "raw_sql": sql,
            "explanation": parsed.get("explanation"),
            "error": err, "attempts": out.attempts}


def ask_screener(question: str, db: Session, prefer_llm: bool = True) -> dict:
    ensure_views()
    llm = {"used": False}
    result = None
    if prefer_llm and LLM.configured():
        llm = _llm_sql(question, db)
        if llm.get("used") and llm.get("sql"):
            result = run_sql(llm["sql"])
            if not result["ok"]:
                llm["fallback_reason"] = result.get("error")
                result = None
    mode = "llm"
    if result is None:
        sql, why = fallback_sql(question, db)
        result = run_sql(sql)
        mode = "deterministic"
        llm["fallback_explanation"] = why
    return {
        "question": question,
        "mode": mode,
        "sql": result.get("sql"),
        "columns": result.get("columns", []),
        "rows": result.get("rows", []),
        "row_count": result.get("row_count", 0),
        "error": result.get("error"),
        "llm": llm,
        "guard": ("Single SELECT only · view allow-list · query-only connection · "
                  "hard row cap 200"),
    }


