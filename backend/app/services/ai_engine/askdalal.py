"""Ask Dalal AI — guarded research copilot over *your own* platform data.

Four capabilities, all grounded in stored real data:

* **Text-to-SQL screener** — natural language → `SELECT` over a small set of
  read-only views. The SQL is generated by the failover LLM when available and
  by a deterministic parser otherwise; **every statement is validated against a
  table allow-list and executed on a query-only connection.**
* **Document Q&A** — hybrid dense + lexical retrieval over the indexed filing
  corpus. Answers quote the retrieved chunks; when the corpus is empty the
  answer says so instead of inventing a filing.
* **CEO Say-vs-Do Credibility Tracker** — quantified commitments extracted from
  the NSE corporate-announcement summary text, then checked against the
  company's own annual statements. Only commitments with a number and a
  measurable metric are scored.
* **Filing semantic diff** — year-over-year changes in the reported line items
  plus thematic flags (margin, leverage, cash conversion, capex). The response
  states its granularity so annual data is never passed off as quarterly.

Nothing here recommends a security.
"""
