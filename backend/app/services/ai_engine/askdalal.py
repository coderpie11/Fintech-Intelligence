_RAG_SYSTEM = (
    "Answer ONLY from the supplied context chunks. If the context does not "
    "contain the answer, say exactly that. Cite chunks as [1], [2]. Never add "
    "outside facts or numbers. Keep the answer under 120 words."
)


def answer_documents(question: str, db: Session, symbol: str | None = None,
                     prefer_llm: bool = True) -> dict:
    hits = rag.search(db, question, symbol=symbol, k=6)
    if not hits.get("hits"):
        return {"question": question, "answer": None, "hits": [],
                "coverage": "empty-corpus",
                "note": hits.get("note") or
                        "No indexed document matches this question."}
    context = "\n\n".join(
        f"[{i + 1}] {h['title']} ({h['doc_kind']}, {h.get('asof') or 'undated'}):\n{h['text']}"
        for i, h in enumerate(hits["hits"]))
    llm = {"used": False}
    answer = None
    if _llm_allowed(prefer_llm):
        try:
            out = LLM.complete(
                f"Question: {question}\n\nContext:\n{context}",
                system=_RAG_SYSTEM, max_tokens=700, route="ask-dalal-rag",
                timeout_s=4)
            answer = out.text
            llm = {"used": True, "provider": out.provider, "model": out.model,
                   "tier": out.tier}
        except LLM.LlmUnavailable as e:
            llm = {"used": False, "error": str(e)[:240]}
    if not answer:
        # Extractive fallback: return the best-matching sentences verbatim.
        best = hits["hits"][0]
        sents = re.split(r"(?<=[.!?])\s+", best["text"])
        answer = " ".join(sents[:3])[:600]
        llm["mode"] = "extractive"
    return {"question": question, "answer": answer,
            "coverage": "grounded",
            "hits": hits["hits"], "dense": hits.get("dense"),
            "scanned": hits.get("scanned"), "llm": llm}


