def _extract_commitments(symbol: str) -> dict:
    """Quantified guidance from the company's own transcript/presentation PDFs.

    NSE announcement *subjects* carry no guidance, so the tracker reads the
    attached documents. Falls back to an explicit empty result, never to
    invented text.
    """
    from app.services.ai_engine import filings
    nse_symbol = _NSE_SYMBOL_ALIASES.get(symbol.upper(), symbol.upper())
    return filings.extract_commitments(nse_symbol)


def _percent_target(quote: str) -> float | None:
    """First percentage stated in a sentence ('15%', '15 percent', '15 pc')."""
    m = re.search(r"(-?\d+(?:\.\d+)?)\s*(?:%|percent|per cent|pc\b)", quote, re.I)
    return float(m.group(1)) if m else None


def _announcement_year(item: dict) -> int | None:
    raw = (item.get("announced") or "").strip()
    m = re.search(r"(19|20)\d{2}", raw)
    return int(m.group(0)) if m else None


_UNVERIFIABLE_CUES = {
    "margin": ("nim", "net interest margin", "casa ratio"),
    "debt_reduction": ("gnpa", "gross npa", "npa ratio"),
    "capex": ("capacity", "stores", "gigawatt", "gw", "order book",
              "capacity addition"),
    "volume_growth": (),  # no matching annual statement line for volumes
}


def _verify(item: dict, statements: dict[str, dict[str, float]]) -> dict:
    metric = item.get("metric_guess")
    cue = (item.get("metric_cue") or "").lower()
    if cue and cue in _UNVERIFIABLE_CUES.get(metric, ()):
        return {**item, "metric": metric, "target": item.get("target_pct"),
                "actual": None, "unit": None, "status": "unverifiable",
                "reason": (f"'{cue}' is not a line item in the platform's annual "
                           "statement extract, so this guidance cannot be checked "
                           "against a reported figure here.")}
    if item.get("scorable") is False:
        return {**item, "metric": metric, "target": None,
                "actual": None, "unit": None, "status": "unverifiable",
                "reason": ("Management stated an absolute quantity "
                           f"({item.get('target_text') or 'no figure'}), not a "
                           "percentage. It is shown for context but cannot be "
                           "compared with a percentage change in the annual "
                           "statement.")}
    periods = sorted(statements.keys(), key=_period_sort_key, reverse=True)
    if len(periods) < 2 or metric is None:
        return {**item, "status": "unverifiable",
                "reason": ("No comparable annual metric was found in the platform's "
                           "statement extract.")}
    latest, prior = periods[0], periods[1]
    cur, old = statements[latest], statements[prior]

    # A commitment announced in the same financial year as the latest statement
    # cannot be verified by that statement yet. Say so instead of scoring it.
    ann_year = _announcement_year(item)
    latest_year = _period_sort_key(latest)[0]
    if ann_year and ann_year >= latest_year:
        return {**item, "metric": metric, "target": None, "actual": None,
                "unit": None, "period_latest": latest, "period_prior": prior,
                "status": "pending",
                "reason": (f"Announced in {ann_year}; the annual statement needed "
                           f"to verify it ({ann_year + 1} onwards) has not been "
                           "reported yet, so no score is assigned.")}

    def chg(key):
        if key in cur and key in old and old[key]:
            return (cur[key] / old[key] - 1) * 100
        return None

    # Only a stated percentage can be compared with a percentage change. An
    # absolute rupee commitment ("₹5,000 crore capex") is recorded but not
    # scored, rather than being silently compared with the wrong unit.
    target = item.get("target_pct")
    if target is None:
        target = _percent_target(item.get("quote") or "")
    actual, unit = None, None
    if metric == "revenue_growth":
        actual, unit = chg("revenue"), "% YoY"
    elif metric == "margin":
        if item.get("level_target"):
            # A target like "EBITDA margin of 18%" is a level, not a change.
            actual, unit = cur.get("opm_pct"), "% margin level"
        else:
            actual, unit = (cur.get("opm_pct") - old.get("opm_pct")
                            if "opm_pct" in cur and "opm_pct" in old else None), "pp change"
    elif metric == "debt_reduction":
        c = chg("borrowings") or chg("total_debt")
        actual, unit = (None if c is None else -c), "% debt reduction"
    elif metric == "capex":
        c = (chg("cwip") or chg("fixed_assets") or chg("ppe"))
        actual, unit = c, "% asset-base growth"
    elif metric == "dividend":
        actual, unit = cur.get("dividend_payout_pct"), "% payout ratio"
    elif metric == "buyback":
        actual, unit = None, "corporate-action ledger"

    status = "unverifiable"
    if actual is not None and target is not None:
        # Directional scoring with a 10% tolerance: a stated target of 15% is
        # met at 13.5% or better because filings round and restate.
        if metric in ("debt_reduction",):
            status = "met" if actual >= target * 0.9 else "missed"
        elif metric in ("margin",):
            status = "met" if actual >= -0.25 else "missed"
        else:
            status = "met" if actual >= target * 0.9 else "missed"
    return {**item, "metric": metric, "target": target, "actual": (
                round(actual, 2) if actual is not None else None),
            "unit": unit, "period_latest": latest, "period_prior": prior,
            "status": status,
            "reason": ("Compared with the company's own annual statement: "
                       f"{latest} vs {prior}." if (actual is not None and target is not None)
                       else "The announcement did not state a percentage target "
                            "this metric can be checked against.")}


def _realized(statements: dict[str, dict[str, float]]) -> dict:
    """What the company actually reported — the 'Do' side of the comparison."""
    periods = sorted(statements.keys(), key=_period_sort_key, reverse=True)
    if len(periods) < 2:
        return {"available": False,
                "note": "Fewer than two annual periods are stored, so no "
                        "year-on-year delivery can be shown."}
    cur, old = statements[periods[0]], statements[periods[1]]

    def chg(key):
        if key in cur and key in old and old[key]:
            return round((cur[key] / old[key] - 1) * 100, 2)
        return None

    return {
        "available": True,
        "latest_period": periods[0], "prior_period": periods[1],
        "revenue_growth_pct": chg("revenue"),
        "operating_margin_pct": cur.get("opm_pct"),
        "operating_margin_change_pp": (round(cur["opm_pct"] - old["opm_pct"], 2)
                                       if "opm_pct" in cur and "opm_pct" in old
                                       else None),
        "borrowings_change_pct": chg("borrowings") or chg("total_debt"),
        "capex_change_pct": chg("cwip") or chg("fixed_assets") or chg("ppe"),
        "dividend_payout_pct": cur.get("dividend_payout_pct"),
        "cfo_to_net_income": (round(cur["cfo"] / cur["net_income"], 2)
                              if cur.get("cfo") and cur.get("net_income") else None),
        "note": ("Reported annual figures from the platform's statement extract. "
                 "This is what the company delivered, regardless of what it "
                 "said it would do."),
    }


def credibility(db: Session, symbol: str) -> dict:
    row = db.query(Instrument).filter_by(kind="EQUITY", symbol=symbol.upper()).one_or_none()
    if not row:
        raise LookupError(f"{symbol} is not a tracked equity.")
    st = _annual_map(row)
    extracted = _extract_commitments(symbol)
    scored = [_verify(i, st) for i in extracted.get("items", [])]
    met = sum(1 for s in scored if s["status"] == "met")
    missed = sum(1 for s in scored if s["status"] == "missed")
    total = met + missed
    events = (db.query(CorporateEvent)
                .filter(CorporateEvent.symbol == symbol.upper())
                .order_by(CorporateEvent.ex_date.desc().nullslast())
                .limit(20).all())
    today = date.today()
    ledger = [{
        "kind": e.kind, "purpose": e.purpose,
        "ex_date": e.ex_date.isoformat() if e.ex_date else None,
        "status": (None if not e.ex_date else
                   "completed (ex-date passed)" if e.ex_date <= today
                   else "scheduled"),
    } for e in events]
    return {
        "symbol": row.symbol, "name": row.name,
        "coverage": {
            "announcements_scanned": extracted.get("announcements", 0),
            "quantified_commitments": len(extracted.get("items", [])),
            "scored": total, "met": met, "missed": missed,
            "pending": sum(1 for s in scored if s["status"] == "pending"),
            "unverifiable": sum(1 for s in scored if s["status"] == "unverifiable"),
        },
        "credibility_score_pct": round(met / total * 100, 1) if total else None,
        "score_note": (f"{met} of {total} quantified commitments were met on the "
                       "company's own subsequent annual numbers."
                       if total else
                       "No quantified commitment has both a stated percentage "
                       "target and a reported annual period to check it against "
                       "yet, so no score is shown. An empty score is not a clean "
                       "record."),
        "commitments": scored,
        "realized": _realized(st),
        "documents_scanned": extracted.get("documents", []),
        "corporate_action_ledger": ledger,
        "method": ("Commitment sentences are taken verbatim from NSE corporate "
                   "announcement summaries. Only sentences containing a number "
                   "and a measurable metric are scored, against the platform's "
                   "annual statement extract. This is a small, auditable sample "
                   "— not a complete history of management guidance."),
        "error": extracted.get("error"),
    }


