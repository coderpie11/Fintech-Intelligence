_THEMES = [
    ("top-line expansion", ("revenue",), 10.0),
    ("operating-margin expansion", ("opm_pct",), None),
    ("leverage rising", ("borrowings", "total_debt"), 15.0),
    ("capex ramp", ("cwip", "fixed_assets", "ppe"), 20.0),
    ("cash conversion weakening", ("cfo",), None),
]


def filing_diff(db: Session, symbol: str, granularity: str = "annual") -> dict:
    row = db.query(Instrument).filter_by(kind="EQUITY", symbol=symbol.upper()).one_or_none()
    if not row:
        raise LookupError(f"{symbol} is not a tracked equity.")
    meta = row.meta or {}
    cons = meta.get("statements_consolidated") or {}
    stand = meta.get("statements_standalone") or {}
    basis = "consolidated" if (cons.get("annual") or {}).get("periods") else "standalone"
    src = cons if basis == "consolidated" else stand
    annual = src.get("annual") or {}
    quarterly = src.get("quarterly") or {}
    q_periods = quarterly.get("periods") or []

    if granularity == "quarterly":
        if not q_periods:
            return {"symbol": symbol, "granularity": "quarterly",
                    "available": False,
                    "note": ("The free filing source has no quarterly columns for "
                             "this company yet. To avoid inventing a comparison, "
                             "the request is answered with the annual diff "
                             "instead — switch granularity to `annual`."),
                    "annual_available": bool((annual.get("periods") or []))}
        periods, sections = q_periods, sections_of(quarterly)
    else:
        periods, sections = annual.get("periods") or [], sections_of(annual)

    if len(periods) < 2:
        return {"symbol": symbol, "granularity": granularity, "available": False,
                "note": "Fewer than two reported periods are stored for this company."}

    order = _newest_indices(periods)
    latest, prior = periods[order[0]], periods[order[1]]
    changes = []
    for sec, items in sections.items():
        for key, vals in (items or {}).items():
            if not isinstance(vals, list):
                continue
            i_cur, i_old = order[0], order[1]
            cur = vals[i_cur] if i_cur < len(vals) else None
            old = vals[i_old] if i_old < len(vals) else None
            if cur is None or old is None:
                continue
            try:
                cur, old = float(cur), float(old)
            except (TypeError, ValueError):
                continue
            pct = round((cur / old - 1) * 100, 2) if old else None
            changes.append({"section": sec, "item": key, "previous": old,
                            "latest": cur,
                            "change_pct": pct,
                            "direction": ("up" if cur > old else
                                          "down" if cur < old else "flat")})
    changes.sort(key=lambda c: abs(c["change_pct"] or 0), reverse=True)
    lookup = {(c["section"], c["item"]): c for c in changes}

    themes = []
    for label, keys, threshold in _THEMES:
        hit = next((lookup.get(("income", k)) or lookup.get(("balance", k))
                    or lookup.get(("cashflow", k)) for k in keys
                    if (lookup.get(("income", k)) or lookup.get(("balance", k))
                        or lookup.get(("cashflow", k)))), None)
        if not hit:
            continue
        if label == "operating-margin expansion" and "opm_pct" in hit["item"]:
            themes.append({**hit, "theme": label})
        elif label == "cash conversion weakening":
            ni = next((lookup.get(("income", k)) for k in ("net_income", "profit")
                       if lookup.get(("income", k))), None)
            if ni and ni["latest"] and hit["latest"] is not None:
                ratio = hit["latest"] / ni["latest"] if ni["latest"] else None
                if ratio is not None and ratio < 0.8:
                    themes.append({**hit, "theme": label,
                                   "note": f"CFO/net income = {ratio:.2f}×"})
        elif threshold is not None and hit["change_pct"] is not None \
                and abs(hit["change_pct"]) >= threshold:
            themes.append({**hit, "theme": label})

    return {
        "symbol": row.symbol, "name": row.name,
        "granularity": granularity if q_periods or granularity != "quarterly" else "annual",
        "basis": basis,
        "available": True,
        "periods": [periods[i] for i in _newest_indices(periods)][:4],
        "compared": [latest, prior],
        "changes": changes[:40],
        "themes": themes,
        "quarterly_periods_available": len(q_periods),
        "note": ("Line-item diff of the company's reported statements. A "
                 "'semantic' change is a line item or theme that moved materially "
                 "between the two periods; it is not an interpretation of "
                 "management intent."),
    }
