_COMMIT_CUE = re.compile(
    r"\b(will|expect|expects|guidance|target|plan|plans|intend|intends|aim|aims|"
    r"commit|commits|forecast|outlook|going forward|confident)\b", re.I)


_MONTHS = {m: i for i, m in enumerate(
    ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct",
     "Nov", "Dec"), 1)}


def _period_sort_key(p: str) -> tuple[int, int]:
    """Sortable (year, month) for labels like 'Mar 2026' or 'Q3 FY26'."""
    m = re.match(r"([A-Za-z]{3})\w*\s+(\d{4})", (p or "").strip())
    if m:
        return (int(m.group(2)), _MONTHS.get(m.group(1)[:3].title(), 0))
    m = re.match(r"\d{4}", (p or "").strip())
    return (int(m.group(0)), 12) if m else (0, 0)


def _newest_indices(periods: list[str]) -> list[int]:
    """Stored series are oldest-first; return indices newest-first."""
    return sorted(range(len(periods)),
                  key=lambda i: _period_sort_key(periods[i]), reverse=True)


def _annual_map(row: Instrument) -> dict:
    st = (row.meta or {}).get("statements_consolidated") or {}
    a = st.get("annual") or {}
    periods = a.get("periods") or []
    sections = sections_of(a)
    out: dict[str, dict[str, float]] = {}
    for sec, items in sections.items():
        for key, vals in (items or {}).items():
            if not isinstance(vals, list):
                continue
            for i, v in enumerate(vals):
                if i >= len(periods) or v is None:
                    continue
                try:
                    out.setdefault(_period_key(periods[i]), {})[key] = float(v)
                except (TypeError, ValueError):
                    continue
    return out


def _period_key(p: str) -> str:
    return p


def _ordered_periods(statements: dict[str, dict[str, float]],
                     fallback: list[str]) -> list[str]:
    """Newest first. Stored periods are already newest-first."""
    return [p for p in fallback if p in statements] or list(statements.keys())


