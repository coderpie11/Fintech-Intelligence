_SECTOR_WORDS = [
    "bank", "banks", "banking", "it", "software", "pharma", "auto", "fmcg",
    "energy", "oil", "gas", "metal", "steel", "cement", "power", "infra",
    "telecom", "realty", "financial", "finance", "insurance", "chemical",
    "textile", "consumer", "capital goods", "defence", "airline", "hotel",
]

# Query word → fragments that can appear in either the stored `sector` or the
# stored `industry`. Matching is done on whole words, so "IT" can never match
# the "it" inside "Capital Goods".
_SECTOR_ALIASES: dict[str, tuple[str, ...]] = {
    "bank": ("banks",), "banks": ("banks",), "banking": ("banks",),
    "it": ("it - software", "information technology"),
    "software": ("it - software",), "pharma": ("pharmaceuticals", "healthcare"),
    "auto": ("automobile",), "fmcg": ("fast moving consumer goods",),
    "energy": ("oil", "petroleum", "power", "gas"),
    "oil": ("oil", "petroleum"), "gas": ("gas",),
    "metal": ("metals",), "steel": ("metals", "iron"),
    "cement": ("cement",), "power": ("power",), "infra": ("construction",),
    "telecom": ("telecommunication",), "realty": ("realty",),
    "financial": ("financial services",), "finance": ("financial services",),
    "insurance": ("insurance",), "chemical": ("chemicals",),
    "textile": ("textiles",), "consumer": ("consumer",),
    "capital goods": ("capital goods",), "defence": ("defense",),
    "airline": ("airline",), "hotel": ("hotel",),
    "healthcare": ("healthcare",),
}


def _sector_clauses(q: str, sectors: list[str]) -> tuple[list[str], list[str]]:
    """Build SQL fragments from sector/industry keywords in the question."""
    clauses: list[str] = []
    notes: list[str] = []

    # 1. A full stored sector name typed by the user wins.
    exact = [s for s in sectors if s and s.lower() in q]
    for s in exact:
        clauses.append("lower(sector) LIKE '%" + s.replace("'", "''").lower() + "%'")
        notes.append(f"sector = {s}")

    # 2. Otherwise map the query's own words through the alias table.
    if not exact:
        for word in _SECTOR_WORDS:
            if not re.search(rf"\b{re.escape(word)}\b", q):
                continue
            for frag in _SECTOR_ALIASES.get(word, (word,)):
                f = frag.replace("'", "''")
                clauses.append(
                    f"(lower(sector) LIKE '%{f}%' OR lower(industry) LIKE '%{f}%')")
            notes.append(f"sector/industry ~ {word}")
    return clauses, notes


def _number_after(q: str, words: tuple[str, ...]) -> float | None:
    pat = r"(?:%s)[^\d\-]{0,18}(-?\d+(?:\.\d+)?)" % "|".join(words)
    m = re.search(pat, q, re.I)
    return float(m.group(1)) if m else None


def _number_before(q: str, words: tuple[str, ...]) -> float | None:
    pat = (r"(-?\d+(?:\.\d+)?)\s*%?\s*(?:"
           + "|".join(words) + ")")
    m = re.search(pat, q, re.I)
    return float(m.group(1)) if m else None


def fallback_sql(question: str, db: Session) -> tuple[str, str]:
    q = question.lower()
    where, order, notes = [], "market_cap DESC", []

    sectors = [r[0] for r in db.execute(text(
        "SELECT DISTINCT sector FROM v_equities WHERE sector IS NOT NULL")
    ).fetchall()]
    clauses, notes = _sector_clauses(q, sectors)
    if clauses:
        where.append("(" + " OR ".join(clauses) + ")")

    bounds = [
        ("pe", ("pe", "p/e", "price to earnings"), ("below", "under", "less than", "cheaper than"), "asc"),
        ("roe", ("roe", "return on equity"), ("above", "over", "more than", "at least"), "desc"),
        ("delivery_pct", ("delivery", "delivery%"), ("above", "over", "more than"), "desc"),
        ("dividend_yield", ("dividend yield", "yield"), ("above", "over", "more than"), "desc"),
        ("market_cap", ("market cap", "marketcap"), ("above", "over", "more than"), "desc"),
    ]
    for field, names, cues, direction in bounds:
        val = _number_after(q, names)
        before = _number_before(q, names)
        if val is None and before is not None:
            val = before
        if val is None:
            continue
        cue = next((c for c in cues if c in q), None)
        if field == "pe":
            op = "<=" if cue in ("below", "under", "less than", "cheaper than") else ">="
        else:
            op = ">=" if direction == "desc" else "<="
        # Literal float — parsed from the question, never user-supplied text.
        where.append(f"{field} {op} {val:g}")
        notes.append(f"{field} {op} {val:g}")

    # Ticker mentions win over everything else for a single-row lookup.
    symbols = [r[0] for r in db.execute(text(
        "SELECT symbol FROM v_equities")).fetchall()]
    mentioned = [s for s in symbols if re.search(rf"\b{re.escape(s)}\b", question, re.I)]
    if len(mentioned) == 1:
        sym = mentioned[0].replace("'", "''")
        where = [f"symbol = '{sym}'"]
        notes = [f"symbol = {mentioned[0]}"]

    top = _number_after(q, ("top", "first", "largest", "highest"))
    limit = int(top) if top and 1 <= top <= 100 else 20
    if "highest" in q or "largest" in q or "top" in q:
        for field, names, _, _ in bounds:
            if any(n in q for n in names) and field != "pe":
                order = f"{field} DESC"
                break

    sql = "SELECT symbol, name, sector, industry, last_price, change_pct, pe, pb, " \
          "dividend_yield, roe, delivery_pct, market_cap FROM v_equities"
    if where:
        sql += " WHERE " + " AND ".join(where)
    sql += f" ORDER BY {order} LIMIT {limit}"
    return sql, "; ".join(notes) or "no filters recognised — ranked by market cap"


